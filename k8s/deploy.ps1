# Applies the whole platform to the current kubectl context and waits for it.
# PowerShell twin of deploy.sh; safe to re-run.
$ErrorActionPreference = 'Stop'

$K8sDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$MonDir = Resolve-Path (Join-Path $K8sDir '..\..\ecommerce-monitoring')
$Ns     = 'ecommerce'

$Context = (kubectl config current-context)
Write-Host "Context : $Context"
if ($Context -ne 'docker-desktop') {
    $reply = Read-Host "That is not docker-desktop. Continue? [y/N]"
    if ($reply -ne 'y' -and $reply -ne 'Y') { exit 1 }
}

# ─── Render monitoring ConfigMaps ────────────────────────────────────────────
# kustomize refuses to read files outside its own root and ecommerce-monitoring
# is a sibling repo, so the configs are rendered here instead of being copied
# in. That keeps ecommerce-monitoring the only place they are edited, shared
# byte-for-byte with the compose stack. See sync-monitoring-config.sh.
function New-ConfigMapDoc {
    param([string]$Name, [string[]]$Paths)
    $cmdArgs = @('create', 'configmap', $Name, '--namespace', $Ns)
    foreach ($p in $Paths) { $cmdArgs += "--from-file=$p" }
    $cmdArgs += @('--dry-run=client', '-o', 'yaml')
    $yaml = & kubectl @cmdArgs
    if ($LASTEXITCODE -ne 0) { throw "failed to render configmap $Name" }
    '---'
    $yaml | Where-Object { $_ -ne '  creationTimestamp: null' }
}

Write-Host "Rendering monitoring config from ecommerce-monitoring/..."
$header = @(
    '# GENERATED by deploy.ps1 / sync-monitoring-config.sh - do not edit.'
    '#'
    '# Source of truth is ../../ecommerce-monitoring/. Edit the files there,'
    '# re-run this script, and re-apply.'
)
$docs = @()
$docs += $header
$docs += New-ConfigMapDoc 'prometheus-config'          @("$MonDir\prometheus\prometheus.yml")
$docs += New-ConfigMapDoc 'prometheus-rules'           @("$MonDir\prometheus\rules")
$docs += New-ConfigMapDoc 'alertmanager-config'        @("$MonDir\alertmanager\alertmanager.yml")
$docs += New-ConfigMapDoc 'loki-config'                @("$MonDir\loki\loki-config.yml")
$docs += New-ConfigMapDoc 'tempo-config'               @("$MonDir\tempo\tempo-config.yml")
$docs += New-ConfigMapDoc 'grafana-datasources'        @("$MonDir\grafana\provisioning\datasources\datasources.yml")
$docs += New-ConfigMapDoc 'grafana-dashboard-provider' @("$MonDir\grafana\provisioning\dashboards\dashboards.yml")
$docs += New-ConfigMapDoc 'grafana-dashboards'         @("$MonDir\grafana\dashboards")
$docs += New-ConfigMapDoc 'blackbox-config'            @("$MonDir\blackbox-exporter\blackbox-config.yml")
$docs += New-ConfigMapDoc 'postgres-exporter-queries'  @("$MonDir\postgres-exporter\queries.yml")
# Not Out-File -Encoding utf8: in Windows PowerShell 5.1 that writes a BOM, and
# the BOM lands at the top of the first YAML document where the parser rejects
# it. WriteAllLines defaults to UTF-8 without one.
[System.IO.File]::WriteAllLines((Join-Path $K8sDir '05-monitoring-config.yaml'), $docs)

# Application secrets live in the git-ignored ..\.env, never in the manifests
# (S-4). init-secrets.ps1 creates it, or adds keys it lacks; it never changes an
# existing value. Pods read Secrets at start, so after rotating a value run
# `kubectl -n ecommerce rollout restart deployment` as well.
Write-Host ""
Write-Host "Creating Secrets from ..\.env..."
& (Join-Path $K8sDir '..\init-secrets.ps1')
$secrets = @{}
Get-Content (Join-Path $K8sDir '..\.env') | ForEach-Object { if ($_ -match '^([A-Z_]+)=(.*)$') { $secrets[$Matches[1]] = $Matches[2] } }
kubectl apply -f (Join-Path $K8sDir '00-namespace.yaml')
$yaml = kubectl -n $Ns create secret generic platform-secrets `
    "--from-literal=JWT_SECRET=$($secrets.JWT_SECRET)" `
    "--from-literal=ADMIN_PASSWORD=$($secrets.ADMIN_PASSWORD)" `
    "--from-literal=GF_SECURITY_ADMIN_USER=$($secrets.GRAFANA_ADMIN_USER)" `
    "--from-literal=GF_SECURITY_ADMIN_PASSWORD=$($secrets.GRAFANA_ADMIN_PASSWORD)" `
    --dry-run=client -o yaml
$yaml | kubectl apply -f -
$yaml = kubectl -n $Ns create secret generic eureka-credentials `
    "--from-literal=EUREKA_USERNAME=$($secrets.EUREKA_USERNAME)" `
    "--from-literal=EUREKA_PASSWORD=$($secrets.EUREKA_PASSWORD)" `
    --dry-run=client -o yaml
$yaml | kubectl apply -f -

Write-Host ""
Write-Host "Applying manifests..."
kubectl apply -k $K8sDir
if ($LASTEXITCODE -ne 0) { throw "kubectl apply failed" }

# Infrastructure first: nothing else clears its init containers until the
# databases, Kafka and Eureka answer.
Write-Host ""
Write-Host "Waiting for databases and Kafka..."
kubectl -n $Ns rollout status statefulset/kafka --timeout=5m
foreach ($db in @('userdb','productdb','catalogdb','orderdb','paymentdb','shippingdb','reviewdb')) {
    kubectl -n $Ns rollout status "statefulset/$db" --timeout=5m
}

Write-Host ""
Write-Host "Waiting for service discovery..."
kubectl -n $Ns rollout status deployment/service-discovery --timeout=5m

# Ten JVMs starting at once on a laptop-sized node contend badly; the startup
# probes allow five minutes each and this timeout has to cover that.
Write-Host ""
Write-Host "Waiting for application services..."
foreach ($svc in @('user-service','product-service','catalog-service','order-service',
                   'payment-service','shipping-service','review-service',
                   'notification-service','api-gateway','frontend')) {
    kubectl -n $Ns rollout status "deployment/$svc" --timeout=10m
}

Write-Host ""
Write-Host "Waiting for monitoring..."
foreach ($svc in @('prometheus','alertmanager','loki','tempo','grafana')) {
    kubectl -n $Ns rollout status "deployment/$svc" --timeout=5m
}

# Grafana only reads GF_SECURITY_ADMIN_PASSWORD when it creates its database, and
# the database lives on a volume, so an existing install keeps its old password
# (S-18) unless it is reset explicitly.
kubectl -n $Ns exec deploy/grafana -- grafana cli admin reset-admin-password $secrets.GRAFANA_ADMIN_PASSWORD | Out-Null
if ($LASTEXITCODE -eq 0) { Write-Host "Grafana admin password synced from ..\.env" }
else { Write-Warning "could not set Grafana's admin password; it may still be the old one" }

Write-Host ""
kubectl -n $Ns get pods -o wide
Write-Host ""
Write-Host "Frontend        http://localhost:3000"
Write-Host "API gateway     http://localhost:8080"
Write-Host "Eureka          http://localhost:8761   (eureka / EUREKA_PASSWORD)"
Write-Host "Grafana         http://localhost:3001   (GRAFANA_ADMIN_USER / GRAFANA_ADMIN_PASSWORD)"
Write-Host "Logins are in ..\.env; ..\init-secrets.ps1 -Print shows them."
Write-Host "Prometheus      http://localhost:9090"
Write-Host "Alertmanager    http://localhost:9093"
Write-Host "Kafka UI        http://localhost:8090"
