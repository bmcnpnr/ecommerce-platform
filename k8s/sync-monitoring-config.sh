#!/usr/bin/env bash
#
# Renders ../../ecommerce-monitoring/** into 05-monitoring-config.yaml as a set
# of ConfigMaps.
#
# Why a generator instead of plain manifests: kustomize refuses to read files
# outside its own root directory, and ecommerce-monitoring is a sibling repo.
# The alternatives were to copy nine config files into k8s/ (two sources of
# truth, guaranteed to drift) or to keep them where they are and render them on
# demand. This is the second. ecommerce-monitoring stays the only place those
# files are edited, and the compose stack keeps reading the exact same bytes.
#
# Re-run after editing anything under ecommerce-monitoring/, then re-apply.
set -euo pipefail

K8S_DIR="$(cd "$(dirname "$0")" && pwd)"
MON_DIR="$(cd "$K8S_DIR/../../ecommerce-monitoring" && pwd)"
OUT="$K8S_DIR/05-monitoring-config.yaml"
NS=ecommerce

cm() {
  # cm <configmap-name> <--from-file arg>...
  local name="$1"; shift
  echo "---"
  kubectl create configmap "$name" --namespace "$NS" "$@" \
    --dry-run=client -o yaml \
    | grep -v '^  creationTimestamp: null$'
}

{
  cat <<'HDR'
# GENERATED by sync-monitoring-config.sh — do not edit.
#
# Source of truth is ../../ecommerce-monitoring/. Edit the files there, re-run
# ./sync-monitoring-config.sh, and re-apply. Committed rather than gitignored
# so that `kubectl apply -k .` works on a fresh clone without running anything
# first, and so config changes are reviewable in the diff.
HDR

  cm prometheus-config          --from-file="$MON_DIR/prometheus/prometheus.yml"
  cm prometheus-rules           --from-file="$MON_DIR/prometheus/rules"
  cm alertmanager-config        --from-file="$MON_DIR/alertmanager/alertmanager.yml"
  cm loki-config                --from-file="$MON_DIR/loki/loki-config.yml"
  cm tempo-config               --from-file="$MON_DIR/tempo/tempo-config.yml"
  cm grafana-datasources        --from-file="$MON_DIR/grafana/provisioning/datasources/datasources.yml"
  cm grafana-dashboard-provider --from-file="$MON_DIR/grafana/provisioning/dashboards/dashboards.yml"
  cm grafana-dashboards         --from-file="$MON_DIR/grafana/dashboards"
  cm blackbox-config            --from-file="$MON_DIR/blackbox-exporter/blackbox-config.yml"
  cm postgres-exporter-queries  --from-file="$MON_DIR/postgres-exporter/queries.yml"
} > "$OUT"

echo "wrote $OUT ($(wc -l < "$OUT") lines) from $MON_DIR"

# Promtail's Kubernetes config is the one monitoring config kept inline in
# 60-monitoring.yaml. Say so when its pipeline has drifted from the compose one
# (a warning only: a drift must not block a deploy, but it must not go unseen).
bash "$K8S_DIR/check-promtail-parity.sh" || echo "WARNING: promtail pipelines differ between compose and Kubernetes (see above)" >&2
